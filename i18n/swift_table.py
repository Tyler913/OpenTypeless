#!/usr/bin/env python3
"""Writes i18n/strings.json into the macOS app as a Swift raw string literal.

SwiftPM's .embedInCode turns a resource into a [UInt8] array literal, one element per byte: for 300 KB of
translations that one generated file took most of TypelessCore's compile time. A single raw string literal compiles
in a fraction of a second and still lives inside the executable, which build-app.sh packages without a resource
bundle.

    python3 i18n/swift_table.py      regenerate the Swift file (check.py does this too when it's out of date)
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "i18n", "strings.json")
TARGET = os.path.join(ROOT, "macos", "Sources", "TypelessCore", "TranslationsJSON.swift")


def render(json_text):
    """The Swift file holding json_text verbatim as Translations.json."""
    # More #s than any run in the text, so neither the closing """# nor an escape like \#n can occur inside it.
    hashes = "#" * (max((len(run) for run in re.findall(r"#+", json_text)), default=0) + 1)
    # A multiline literal drops the line break just before its closing delimiter: the extra "\n" keeps the text's own.
    return (
        "// Generated by i18n/swift_table.py from i18n/strings.json. Don't edit: change strings.json and run\n"
        "// python3 i18n/check.py, which regenerates this file.\n"
        "\n"
        "extension Translations {\n"
        "    /// The contents of i18n/strings.json.\n"
        f'    static let json = {hashes}"""\n'
        f'{json_text}\n'
        f'"""{hashes}\n'
        "}\n"
    )


def expected():
    with open(SOURCE, encoding="utf-8", newline="") as f:
        return render(f.read())


def current():
    try:
        with open(TARGET, encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


def write():
    """Regenerates the Swift file; returns True if it changed."""
    text = expected()
    if current() == text:
        return False
    with open(TARGET, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True


if __name__ == "__main__":
    print(f"{os.path.relpath(TARGET, ROOT)}: {'updated' if write() else 'already up to date'}")
